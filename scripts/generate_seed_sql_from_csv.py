import os
import csv

CSV_DIR = os.path.join("data", "institutional")
SQL_OUTPUT = os.path.join("supabase", "seed_large.sql")

def escape_sql(val):
    if val is None:
        return "null"
    return "'" + str(val).replace("'", "''") + "'"

def generate_seed():
    # Read all CSVs
    with open(os.path.join(CSV_DIR, "departments.csv"), encoding="utf-8") as f:
        depts = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "year_shifts.csv"), encoding="utf-8") as f:
        shifts = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "time_slots.csv"), encoding="utf-8") as f:
        slots = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "rooms.csv"), encoding="utf-8") as f:
        rooms = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "sections.csv"), encoding="utf-8") as f:
        sections = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "courses.csv"), encoding="utf-8") as f:
        courses = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "faculty.csv"), encoding="utf-8") as f:
        faculty = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "faculty_qualifications.csv"), encoding="utf-8") as f:
        quals = list(csv.DictReader(f))
    with open(os.path.join(CSV_DIR, "section_courses.csv"), encoding="utf-8") as f:
        sec_courses = list(csv.DictReader(f))

    lines = []
    lines.append("-- ===========================================================================")
    lines.append("-- TS-SC: Institutional Large-Scale Seed Script (Dual-Shift University Model)")
    lines.append("-- Scope: 75 Sections | 101 Rooms | 100 Faculty | 112 Courses | 40 Time Slots")
    lines.append("-- Shifts: Year 1 & 4 -> Shift 1 (08:15-14:45) | Year 2 & 3 -> Shift 2 (10:15-16:45)")
    lines.append("-- Common Lunch: 12:15 to 12:45")
    lines.append("-- ===========================================================================")
    lines.append("")
    lines.append("-- Step 1: Ensure columns from migrations 0001-0015 exist")
    lines.append("alter table if exists sections")
    lines.append("  add column if not exists batch_count int not null default 1 check (batch_count >= 1),")
    lines.append("  add column if not exists code text unique,")
    lines.append("  add column if not exists passkey text not null default substring(md5(random()::text), 1, 6),")
    lines.append("  add column if not exists shift int not null default 1 check (shift in (1, 2)),")
    lines.append("  add column if not exists academic_year int default 1 check (academic_year between 1 and 4);")
    lines.append("")
    lines.append("alter table if exists courses")
    lines.append("  add column if not exists is_elective boolean not null default false,")
    lines.append("  add column if not exists lectures_per_week int not null default 0,")
    lines.append("  add column if not exists tutorials_per_week int not null default 0,")
    lines.append("  add column if not exists practicals_per_week int not null default 0;")
    lines.append("")
    lines.append("alter table if exists timetable_versions")
    lines.append("  add column if not exists violations jsonb not null default '{}';")
    lines.append("")
    lines.append("alter table if exists timetable_entries")
    lines.append("  add column if not exists batch int default null check (batch is null or batch >= 1);")
    lines.append("")
    lines.append("create table if not exists academic_year_shifts (")
    lines.append("  institution_id uuid not null references institutions(id) on delete cascade,")
    lines.append("  academic_year int not null check (academic_year between 1 and 4),")
    lines.append("  shift int not null check (shift in (1, 2)),")
    lines.append("  timing_label text not null,")
    lines.append("  starts_at time not null,")
    lines.append("  ends_at time not null,")
    lines.append("  updated_at timestamptz not null default now(),")
    lines.append("  primary key (institution_id, academic_year)")
    lines.append(");")
    lines.append("")
    lines.append("-- Step 2: Wipe all previous data & seed freshly in a single atomic transaction")
    lines.append("do $$")
    lines.append("declare")
    lines.append("  v_inst uuid;")
    lines.append("  v_dept_cse uuid; v_dept_aids uuid; v_dept_it uuid; v_dept_ind uuid;")
    lines.append("  v_prog uuid;")
    lines.append("  ")
    lines.append("begin")
    lines.append("  -- Unlink foreign keys from profiles so existing user auth logins remain intact")
    lines.append("  update profiles set section_id = null, faculty_id = null;")
    lines.append("")
    lines.append("  -- Wipe previous transactional, operational, and scheduling data")
    lines.append("  delete from substitution_penalties;")
    lines.append("  delete from substitution_candidates;")
    lines.append("  delete from substitution_requests;")
    lines.append("  delete from timetable_entries;")
    lines.append("  delete from timetable_versions;")
    lines.append("")
    lines.append("  -- Wipe previous mappings & constraints")
    lines.append("  delete from section_courses;")
    lines.append("  if exists (select 1 from information_schema.tables where table_name = 'program_courses') then")
    lines.append("    delete from program_courses;")
    lines.append("  end if;")
    lines.append("  delete from faculty_qualifications;")
    lines.append("  delete from elective_slot_blocks;")
    lines.append("  delete from constraints;")
    lines.append("  delete from time_slots;")
    lines.append("  delete from academic_year_shifts;")
    lines.append("")
    lines.append("  -- Wipe previous core entities")
    lines.append("  delete from courses;")
    lines.append("  delete from rooms;")
    lines.append("  delete from sections;")
    lines.append("  delete from programs;")
    lines.append("  delete from departments;")
    lines.append("  delete from faculty;")
    lines.append("  delete from institutions;")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 1. Institution & Departments")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  insert into institutions (name) values ('Institute of Engineering & Technology') returning id into v_inst;")
    lines.append("  insert into departments (institution_id, name) values (v_inst, 'Computer Science & Engineering') returning id into v_dept_cse;")
    lines.append("  insert into departments (institution_id, name) values (v_inst, 'Artificial Intelligence & Data Science') returning id into v_dept_aids;")
    lines.append("  insert into departments (institution_id, name) values (v_inst, 'Information Technology') returning id into v_dept_it;")
    lines.append("  insert into departments (institution_id, name) values (v_inst, 'Industry Integrated Programs (TCS/IBM/Apple)') returning id into v_dept_ind;")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 2. Academic Year Shifts (Admin Configurable)")
    lines.append("  -- -------------------------------------------------------------------------")
    for s in shifts:
        lines.append(f"  insert into academic_year_shifts (institution_id, academic_year, shift, timing_label, starts_at, ends_at)")
        lines.append(f"  values (v_inst, {s['academic_year']}, {s['shift']}, {escape_sql(s['timing_label'])}, {escape_sql(s['starts_at'])}, {escape_sql(s['ends_at'])});")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 3. Time Slots (5 Days x 8 Periods with Common Lunch 12:15-12:45)")
    lines.append("  -- -------------------------------------------------------------------------")
    for sl in slots:
        lines.append(f"  insert into time_slots (institution_id, day_of_week, period, starts_at, ends_at)")
        lines.append(f"  values (v_inst, {sl['day_of_week']}, {sl['period']}, {escape_sql(sl['starts_at'])}, {escape_sql(sl['ends_at'])});")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 4. Rooms (81 Classrooms + 20 Labs = 101 Rooms)")
    lines.append("  -- -------------------------------------------------------------------------")
    for r in rooms:
        lines.append(f"  insert into rooms (institution_id, name, room_type, capacity)")
        lines.append(f"  values (v_inst, {escape_sql(r['code'])}, {escape_sql(r['room_type'])}, {r['capacity']});")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 5. Academic Programs (4 Programs x 4 Years)")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  insert into programs (id, department_id, name) values ('10000000-0000-0000-0000-000000000001', v_dept_cse, 'B.Tech CSE Year 1');")
    lines.append("  insert into programs (id, department_id, name) values ('10000000-0000-0000-0000-000000000002', v_dept_cse, 'B.Tech CSE Year 2');")
    lines.append("  insert into programs (id, department_id, name) values ('10000000-0000-0000-0000-000000000003', v_dept_cse, 'B.Tech CSE Year 3');")
    lines.append("  insert into programs (id, department_id, name) values ('10000000-0000-0000-0000-000000000004', v_dept_cse, 'B.Tech CSE Year 4');")
    lines.append("  insert into programs (id, department_id, name) values ('20000000-0000-0000-0000-000000000001', v_dept_aids, 'B.Tech AI-DS Year 1');")
    lines.append("  insert into programs (id, department_id, name) values ('20000000-0000-0000-0000-000000000002', v_dept_aids, 'B.Tech AI-DS Year 2');")
    lines.append("  insert into programs (id, department_id, name) values ('20000000-0000-0000-0000-000000000003', v_dept_aids, 'B.Tech AI-DS Year 3');")
    lines.append("  insert into programs (id, department_id, name) values ('20000000-0000-0000-0000-000000000004', v_dept_aids, 'B.Tech AI-DS Year 4');")
    lines.append("  insert into programs (id, department_id, name) values ('30000000-0000-0000-0000-000000000001', v_dept_it, 'B.Tech IT Year 1');")
    lines.append("  insert into programs (id, department_id, name) values ('30000000-0000-0000-0000-000000000002', v_dept_it, 'B.Tech IT Year 2');")
    lines.append("  insert into programs (id, department_id, name) values ('30000000-0000-0000-0000-000000000003', v_dept_it, 'B.Tech IT Year 3');")
    lines.append("  insert into programs (id, department_id, name) values ('30000000-0000-0000-0000-000000000004', v_dept_it, 'B.Tech IT Year 4');")
    lines.append("  insert into programs (id, department_id, name) values ('40000000-0000-0000-0000-000000000001', v_dept_ind, 'Industry Programs Year 1');")
    lines.append("  insert into programs (id, department_id, name) values ('40000000-0000-0000-0000-000000000002', v_dept_ind, 'Industry Programs Year 2');")
    lines.append("  insert into programs (id, department_id, name) values ('40000000-0000-0000-0000-000000000003', v_dept_ind, 'Industry Programs Year 3');")
    lines.append("  insert into programs (id, department_id, name) values ('40000000-0000-0000-0000-000000000004', v_dept_ind, 'Industry Programs Year 4');")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 6. Sections (75 Sections with Shifts & Passkeys)")
    lines.append("  -- -------------------------------------------------------------------------")
    dept_prog_prefix = {"CSE": "1", "AIDS": "2", "IT": "3", "IND": "4"}
    for s in sections:
        p_id = f"'{dept_prog_prefix[s['department_code']]}0000000-0000-0000-0000-00000000000{s['academic_year']}'"
        lines.append(f"  insert into sections (program_id, name, semester, academic_year, shift, strength, batch_count, code, passkey)")
        lines.append(f"  values ({p_id}, {escape_sql(s['code'])}, {s['semester']}, {s['academic_year']}, {s['shift']}, {s['strength']}, {s['batch_count']}, {escape_sql(s['code'])}, {escape_sql(s['passkey'])});")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 7. Courses (Real University Degree Curriculum)")
    lines.append("  -- -------------------------------------------------------------------------")
    dept_var_map = {"CSE": "v_dept_cse", "AIDS": "v_dept_aids", "IT": "v_dept_it", "IND": "v_dept_ind"}
    for c in courses:
        d_var = dept_var_map.get(c['department_code'], 'v_dept_cse')
        credits_val = int(c.get('credits', c['sessions_per_week']))
        l_val = int(c.get('lectures_per_week', 0))
        t_val = int(c.get('tutorials_per_week', 0))
        p_val = int(c.get('practicals_per_week', 0))
        is_elec = str(c.get('is_elective', False)).lower()
        lines.append(f"  insert into courses (department_id, code, name, credits, lectures_per_week, tutorials_per_week, practicals_per_week, sessions_per_week, lab_required, is_elective)")
        lines.append(f"  values ({d_var}, {escape_sql(c['code'])}, {escape_sql(c['name'])}, {credits_val}, {l_val}, {t_val}, {p_val}, {c['sessions_per_week']}, {str(c['lab_required']).lower()}, {is_elec});")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 8. Faculty (121 Instructors, Max Load 24 hr/week)")
    lines.append("  -- -------------------------------------------------------------------------")
    for f in faculty:
        d_var = dept_var_map[f['department_code']]
        lines.append(f"  insert into faculty (institution_id, name, email, department_id, max_weekly_load)")
        lines.append(f"  values (v_inst, {escape_sql(f['name'])}, {escape_sql(f['email'])}, {d_var}, {f['max_weekly_load']});")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 9. Qualifications: Universal (Any faculty can teach any course - no table inserts needed)")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 10. Section-Course Curriculum Mapping (525 Mappings)")
    lines.append("  -- -------------------------------------------------------------------------")
    for sc in sec_courses:
        s_code = sc['section_code']
        c_code = sc['course_code']
        lines.append(f"  insert into section_courses (section_id, course_id)")
        lines.append(f"  values ((select id from sections where code = {escape_sql(s_code)} limit 1), (select id from courses where code = {escape_sql(c_code)} limit 1));")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 11. Generic Elective Reserved Slot Blocks (Thu & Fri Last Two Periods of Each Shift)")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  insert into elective_slot_blocks (time_slot_id)")
    lines.append("  select id from time_slots")
    lines.append("  where institution_id = v_inst")
    lines.append("    and day_of_week in (4, 5)")
    lines.append("    and period in (5, 6, 7, 8);")
    lines.append("")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  -- 12. Optimization Weights")
    lines.append("  -- -------------------------------------------------------------------------")
    lines.append("  insert into constraints (institution_id, key, value, kind) values")
    lines.append("    (v_inst, 'gap_weight', '{\"value\": 10}', 'soft'),")
    lines.append("    (v_inst, 'day_spread_weight', '{\"value\": 5}', 'soft'),")
    lines.append("    (v_inst, 'load_balance_weight', '{\"value\": 5}', 'soft');")
    lines.append("")
    lines.append("end $$;")
    lines.append("")

    with open(SQL_OUTPUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated complete SQL seed script ({len(lines)} lines) at {SQL_OUTPUT}")

if __name__ == "__main__":
    generate_seed()

